import test from "node:test";
import assert from "node:assert/strict";
import { execFile } from "node:child_process";
import { promisify } from "node:util";
import { mkdtemp, mkdir, readFile, readdir, rm, writeFile } from "node:fs/promises";
import os from "node:os";
import path from "node:path";

const exec = promisify(execFile);
const root = path.resolve(".");
test("packed exact initializer applies only its accepted fresh plan and leaves planning passive", { timeout: 120_000 }, async (t) => {
  const directory = await mkdtemp(path.join(os.tmpdir(), "foundry-407-packed-"));
  t.after(() => rm(directory, { recursive: true, force: true }));
  const packs = path.join(directory, "packs");
  const consumer = path.join(directory, "consumer");
  await mkdir(packs);
  await mkdir(consumer);
  await exec("pnpm", ["pack", "--ignore-scripts", "--pack-destination", packs], { cwd: root });
  await exec("npm", ["pack", path.join(root, "initializer"), "--offline", "--ignore-scripts", "--silent", "--pack-destination", packs], { cwd: consumer });
  const tarballs = (await readdir(packs)).map((name) => path.join(packs, name));
  assert.equal(tarballs.length, 2);
  await exec("npm", ["install", "--offline", "--ignore-scripts", "--no-audit", "--no-fund", "--no-save", "--package-lock=false", ...tarballs], { cwd: consumer });
  const foundry = path.join(consumer, "node_modules/@eff3ct/agent-foundry/dist/index.js");
  const initializer = path.join(consumer, "node_modules/@eff3ct/create-agent-foundry/bin/create-agent-foundry.cjs");
  const config = path.join(directory, "setup.json");
  await writeFile(config, await readFile(path.join(root, "test/fixtures/matt-first.json")));
  const target = path.join(directory, "project");
  const args = ["--target", target, "--config", config, "--non-interactive"];
  const preview = JSON.parse((await exec(process.execPath, [foundry, "plan", ...args])).stdout);
  await assert.rejects(exec(process.execPath, [initializer, target, "--config", config, "--non-interactive"]), (error) => {
    assert.equal(JSON.parse(error.stdout).diagnostics.at(-1).code, "acceptance_required");
    return true;
  });
  const applied = JSON.parse((await exec(process.execPath, [initializer, target, "--config", config, "--non-interactive", "--accept-plan", preview.plan_digest])).stdout);
  assert.equal(applied.status, "applied");
  assert.equal(applied.integrity, "verified");
  assert.equal(applied.setup, "incomplete");
  const provenance = JSON.parse(await readFile(path.join(target, ".factory/provenance.json")));
  assert.equal(provenance.candidate.candidate_digest, preview.candidate.candidate_digest);
  const startup = JSON.parse((await exec(process.execPath, [path.join(target, "start.mjs"), "--json"], { cwd: target })).stdout);
  assert.equal(startup.mode, "USABLE");
  assert.equal(startup.next_action.started, false);
  const verified = JSON.parse((await exec(process.execPath, [foundry, "verify", ...args])).stdout);
  assert.equal(verified.integrity, "verified");
});
